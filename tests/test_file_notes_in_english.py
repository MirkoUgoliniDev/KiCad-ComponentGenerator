@pytest.fixture(scope="module")
def write_vrml():
    """`_write_vrml` of the FreeCAD script, taken without importing FreeCAD."""
    tree = ast.parse(SCRIPT.read_text(encoding="utf-8"))
    body = [node for node in tree.body
            if (isinstance(node, ast.FunctionDef) and node.name in ("_write_vrml", "_hex_to_rgb"))
            or (isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "_VRML_SCALE"
                                                     for t in node.targets))]
    assert len(body) == 3
    namespace = {}
    exec(compile(ast.Module(body=body, type_ignores=[]), "<vrml>", "exec"), namespace)
    return namespace["_write_vrml"]


class _Point:
    """A FreeCAD vector stand-in with x, y, z."""

    def __init__(self, x, y, z):
        self.x, self.y, self.z = x, y, z


class _Part:
    """A FreeCAD object stand-in: only its Name reaches the file."""

    def __init__(self, name):
        self.Name = name


def test_the_vrml_header_comment_is_english(write_vrml, tmp_path):
    path = tmp_path / "m.wrl"
    triangle = ([_Point(0, 0, 0), _Point(1, 0, 0), _Point(0, 1, 0)], [(0, 1, 2)])
    write_vrml(path, [(_Part("Body"), "#202020", triangle)])
    text = path.read_text(encoding="utf-8")
    assert text.startswith("#VRML V2.0 utf8\n# Generated by KiCadGen-Tool")
    assert italian_words(text) == []


def test_the_face_text_solids_are_named_in_english():
    """@brief The object name of the body texts reaches the STEP and the VRML: English."""
    source = SCRIPT.read_text(encoding="utf-8")
    assert 'add(f"Silkscreen{i}"' in source and 'add(f"Serigrafia' not in source
