"""@brief The fixed texts the generators write into KiCad files are English (user decision 2026-11-15).

Every note, default description and comment a generator writes into a
.kicad_mod, .kicad_sym or .wrl is in the file language
`core.footprint.FOOTPRINT_TEXT_LANGUAGE`, English like the rest of a KiCad
library (KLC). Messages shown in the interface stay translated and are not
checked here.

Each family gets a positive case (a part whose data carry an estimate or a
missing pin 1, so the generator MUST write its note, and the note is
English) and a negative twin (the same part with the value declared, so no
note is written at all). The Italian-word scan itself is checked against the
notes the generators wrote before 2026-11-15, so it cannot pass vacuously.
"""

from __future__ import annotations

import ast
import re
from pathlib import Path

import pytest

from kicadgen.core import footprint as footprint_module
from kicadgen.core.package_geometry import PackageGeometry, PinSpec
from kicadgen.core.silk import PIN_ONE_UNMARKED_NOTE
from kicadgen.generators.castellated_module import (
    CONTACT_HALF_AND_THROUGH, CONTACT_HALF_HOLE, SMD_WITH_DRILLED_PADS_NOTE, CastellatedModuleParams,
    CastellatedSide, build_castellated_module)
from kicadgen.generators.package import (ESTIMATED_BODY_CENTRE_NOTE, ESTIMATED_PADS_NOTE, build_package)
from kicadgen.generators.pin_header import ROW_SPACING_ASSUMED_NOTE, PinHeaderParams, build_pin_header
from kicadgen.generators.symbol import SymbolMetadata, SymbolPin, serialize_symbol

SCRIPT = Path(__file__).resolve().parents[1] / "kicadgen" / "cad3d" / "freecad_build_body.py"

#: Italian words and stems the generators used in their file notes before
#: 2026-11-15. Whole words, so the English «module», «centre» or «pad» never
#: match; a stem («stimat», «assunt», «piazzol») covers its inflections.
ITALIAN_WORDS = re.compile(
    r"\b(stimat\w*|for[oi]|semi-for[oi]|piazzol\w*|verificar\w*|marcat[oi]|generic[oi]|dimensioni|"
    r"assunt\w*|misurat\w*|lat[oi]|contatti|passo|distanza|righe|generato|nessun\w*|corona|"
    r"modulo|bordo|unita'?|convenzione|di proposito|rifusione|Serigrafia\w*)\b",
    re.IGNORECASE)

#: The notes as the generators wrote them before 2026-11-15 (Italian).
NOTES_BEFORE_2026_11_15 = [
    "pin 1 non marcato: nessun pad 1",
    "lato sinistro: semi-foro 1.70mm, centro semi-foro a 0.65mm dal bordo assunti, non misurati (stima)",
    "distanza fra le righe non dichiarata: assunta uguale al passo (stima)",
    "Tipo SMD di proposito anche con piazzole forate: il modulo si posa e si salda a rifusione, "
    "i fori non ospitano pin.",
    "Modulo castellated 10x12mm, 3 contatti su 1 lati, generato con kicadgen_tool",
    "Header/modulo THT 2x3, passo 2.54mm, distanza righe 2.54mm, generato con kicadgen_tool",
    "foro o piazzola stimati sui pad 1: da verificare sul disegno",
    "centro del corpo stimato dal campo dei pad",
    "soic package generico",
    "# Generato da KiCadGen-Tool (coordinate in unita' 0.1 inch, come da convenzione KiCad)",
]


def italian_words(text: str) -> list[str]:
    """@brief The Italian words of ITALIAN_WORDS found in `text`."""
    return [match.group(0) for match in ITALIAN_WORDS.finditer(text)]


def test_the_file_language_is_english():
    assert footprint_module.FOOTPRINT_TEXT_LANGUAGE == "en"


@pytest.mark.parametrize("italian", NOTES_BEFORE_2026_11_15)
def test_the_scan_finds_every_note_written_before_the_decision(italian):
    """@brief The scan is not vacuous: each pre-2026-11-15 Italian note is caught."""
    assert italian_words(italian)


@pytest.mark.parametrize("english", [
    PIN_ONE_UNMARKED_NOTE, ROW_SPACING_ASSUMED_NOTE, SMD_WITH_DRILLED_PADS_NOTE,
    ESTIMATED_PADS_NOTE, ESTIMATED_BODY_CENTRE_NOTE])
def test_the_scan_passes_the_english_notes(english):
    """@brief ...and passes their English wording, word for word."""
    assert italian_words(english) == []


# -- Pin header -----------------------------------------------------------------

def test_a_pin_header_with_an_assumed_row_spacing_writes_an_english_note():
    text = build_pin_header(PinHeaderParams(rows=2, cols=3)).render()
    assert ROW_SPACING_ASSUMED_NOTE in text and "generated by kicadgen_tool" in text
    assert italian_words(text) == []


def test_a_pin_header_with_declared_row_spacing_writes_no_estimate_note():
    text = build_pin_header(PinHeaderParams(rows=2, cols=3, row_spacing=7.62)).render()
    assert "estimate" not in text and italian_words(text) == []


def test_a_pin_header_without_pin_one_says_so_in_english():
    lettered = build_pin_header(PinHeaderParams(rows=1, cols=2, pitch=2.54,
                                                pin_map={"K": (0, 0), "A": (0, 1)})).render()
    numbered = build_pin_header(PinHeaderParams(rows=1, cols=2, pitch=2.54)).render()
    assert PIN_ONE_UNMARKED_NOTE in lettered and PIN_ONE_UNMARKED_NOTE not in numbered
    assert italian_words(lettered) == [] and italian_words(numbered) == []


# -- Castellated module ---------------------------------------------------------

def _module(**declared):
    side = CastellatedSide(edge="left", count=3, pitch=2.54, contact_style=CONTACT_HALF_HOLE)
    return CastellatedModuleParams(body_length=10, body_width=12, sides=[side], **declared)


def test_a_module_with_assumed_sizes_records_them_in_english():
    text = build_castellated_module(_module()).render()
    assert "left side: " in text and "assumed, not measured (estimate)" in text
    assert "Castellated module 10x12mm, 3 contacts on 1 sides" in text
    assert italian_words(text) == []


def test_a_module_with_declared_sizes_writes_no_assumption():
    # CONTRACT CHANGED 2026-11-16 (review follow-up): the overhang left at its
    # reference is an assumed size, so «every size declared» includes it.
    text = build_castellated_module(_module(hole_diameter=1.0, hole_inset=0.3, pad_length=2.5,
                                            pad_width=1.2, pad_overhang=1.4)).render()
    assert "assumed" not in text and italian_words(text) == []


def test_a_module_with_drilled_smd_pads_explains_it_in_english():
    side = CastellatedSide(edge="left", count=3, pitch=2.54, contact_style=CONTACT_HALF_AND_THROUGH)
    drilled = build_castellated_module(CastellatedModuleParams(body_length=10, body_width=12,
                                                               sides=[side])).render()
    plain = build_castellated_module(_module()).render()
    assert SMD_WITH_DRILLED_PADS_NOTE in drilled and SMD_WITH_DRILLED_PADS_NOTE not in plain
    assert italian_words(drilled) == []


# -- Package --------------------------------------------------------------------

def _package(*, origin="body_center", numbers=("1", "2"), sources=None):
    return PackageGeometry(name="P", family="soic", body_length_mm=4.0, body_width_mm=2.0, origin=origin,
                           pins=[PinSpec(number=numbers[0], x_mm=-2.5, y_mm=0, pad_length_mm=1.2,
                                         pad_width_mm=1.2, sources=sources),
                                 PinSpec(number=numbers[1], x_mm=2.5, y_mm=0, pad_length_mm=1.2,
                                         pad_width_mm=1.2)])


def test_a_package_with_estimates_and_no_pin_one_writes_english_notes():
    text = build_package(_package(origin="pin1", numbers=("K", "A"),
                                  sources={"pad_size": "estimated"})).render()
    for note in (ESTIMATED_BODY_CENTRE_NOTE, PIN_ONE_UNMARKED_NOTE,
                 ESTIMATED_PADS_NOTE.format(numbers="K"), "soic generic package"):
        assert note in text
    assert italian_words(text) == []


def test_a_package_read_from_the_drawing_writes_no_estimate_note():
    text = build_package(_package(sources={"pad_size": "read"})).render()
    assert "estimated" not in text and "not marked" not in text
    assert italian_words(text) == []


# -- Symbol ---------------------------------------------------------------------

def test_the_symbol_writer_adds_no_text_of_its_own():
    """@brief Without metadata the symbol file holds no description text at all.

    The negative twin: a description given by the project reaches the file
    verbatim, never translated or extended by the program -- the user's own
    text is theirs, the file language rules the program's notes only.
    """
    bare = serialize_symbol("M", [SymbolPin("1", "A")])
    assert '(property "Description" ""' in bare and italian_words(bare) == []
    given = serialize_symbol("M", [SymbolPin("1", "A")],
                             metadata=SymbolMetadata(description="Relè di segnale"))
    assert '(property "Description" "Relè di segnale"' in given


